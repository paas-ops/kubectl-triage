package bundle

import (
	"fmt"
	"os"
	"path/filepath"
	"time"
)

// Scaffold creates a minimal, runnable incident bundle. It refuses to overwrite
// an existing incident.yaml so users do not lose a real incident by accident.
//
// All synthetic timestamps are derived from the current time and kept inside a
// narrow window so that a freshly scaffolded bundle never reports stale evidence
// or clock skew on the very first analyze run.
func Scaffold(dir string) error {
	if _, err := os.Stat(filepath.Join(dir, IncidentFile)); err == nil {
		return fmt.Errorf("%s already exists; choose a new directory", filepath.Join(dir, IncidentFile))
	}
	for _, sub := range []string{"k8s", "logs", "metrics"} {
		if err := os.MkdirAll(filepath.Join(dir, sub), 0o755); err != nil {
			return err
		}
	}

	base := time.Now().UTC().Truncate(time.Second).Add(-10 * time.Minute)
	ts := func(offset time.Duration) string { return base.Add(offset).Format(time.RFC3339) }
	epoch := func(offset time.Duration) int64 { return base.Add(offset).Unix() }

	incident := fmt.Sprintf(`id: example-oom
alertname: KubePodCrashLooping
severity: critical
cluster: local
namespace: checkout
workload: checkout-api
observed_at: %s
collected_at: %s
source: example
`, ts(0), ts(5*time.Second))

	files := map[string]string{
		IncidentFile: incident,
		"k8s/events.json": fmt.Sprintf(`{
  "kind": "EventList",
  "items": [
    {
      "type": "Warning",
      "reason": "OOMKilled",
      "message": "Container checkout-api was OOMKilled (exitCode=137)",
      "involvedObject": {"kind": "Pod", "name": "checkout-api-7d9f"},
      "firstTimestamp": "%s",
      "lastTimestamp": "%s"
    }
  ]
}
`, ts(3*time.Second), ts(3*time.Second)),
		"logs/app.log": fmt.Sprintf(`%s INFO starting checkout-api
%s WARN memory usage 498MiB / 512MiB
%s ERROR container terminated: OOMKilled (exitCode=137)
%s INFO restarting container
`, ts(0), ts(2*time.Second), ts(3*time.Second), ts(4*time.Second)),
		"metrics/memory.json": fmt.Sprintf(`{
  "status": "success",
  "data": {
    "resultType": "matrix",
    "result": [{"metric": {"pod": "checkout-api-7d9f"}, "values": [[%d, "498"], [%d, "512"]]}]
  }
}
`, epoch(-2*time.Second), epoch(2*time.Second)),
		"README.md": `# Example incident bundle

This is a synthetic OOMKilled example generated by ` + "`kubectl triage init`" + `.

- Replace ` + "`incident.yaml`" + ` with your incident metadata.
- Drop redacted ` + "`kubectl`" + `, Prometheus, Loki and log exports under the folders.
- Run ` + "`kubectl triage validate .`" + ` before analysis.
`,
	}
	for rel, content := range files {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if _, err := os.Stat(path); err == nil {
			continue
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}
