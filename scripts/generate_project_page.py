"""Generate the bilingual GitHub Pages project documentation pages (stdlib only).

Default mode renders both pages from the project-document sources:

    docs/PROJECT.md     -> site/project.html     (English, lang="en")
    docs/PROJECT-zh.md  -> site/project-zh.html  (Chinese, lang="zh-CN")

Each generated page is a self-contained static HTML rendering that reuses
site/styles.css. Only plain href hyperlinks may point outside the site; no
external resources (scripts, fonts, images, CDN) are emitted.

Usage:
    python3 scripts/generate_project_page.py
    python3 scripts/generate_project_page.py --check
    python3 scripts/generate_project_page.py --source docs/PROJECT.md --output site/project.html --lang en
"""

