# CLI
# ---------------------------------------------------------------------------
def fail(message):
    sys.stderr.write("generate_project_page: " + message + "\n")
    return None


def parse_args(argv):
    opts = {"check": False, "source": None, "output": None, "lang": None}
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg in ("-h", "--help"):
            print(USAGE, end="")
            raise SystemExit(0)
        if arg == "--check":
            opts["check"] = True
            i += 1
            continue
        if arg in ("--source", "--output", "--lang"):
            if i + 1 >= len(argv):
                fail("missing value for " + arg)
                raise SystemExit(2)
            opts[arg[2:]] = argv[i + 1]
            i += 2
            continue
        fail("unknown argument: " + arg)
        raise SystemExit(2)
    explicit = [opts["source"], opts["output"], opts["lang"]]
    if any(value is not None for value in explicit) and not all(value is not None for value in explicit):
        fail("--source, --output and --lang must be used together")
        raise SystemExit(2)
    if opts["lang"] is not None and opts["lang"] not in ("en", "zh"):
        fail("--lang must be en or zh")
        raise SystemExit(2)
    return opts


def resolve(path_text):
    path = Path(path_text)
    if not path.is_absolute():
        path = ROOT / path
    return path


def build_page(source, lang):
    source_rel = source.relative_to(ROOT).as_posix()
    lines = source.read_text(encoding="utf-8").splitlines()
    article = render_blocks(lines)
    # The project sources carry a language-switch line below the H1. Point it at the
    # local counterpart page instead of the raw GitHub Markdown file so readers stay
    # on the static site; the header control does the same thing.
    if lang == "en":
        article = article.replace(
            'href="' + GH_BLOB + 'docs/PROJECT-zh.md">',
            'href="project-zh.html" hreflang="zh-CN" lang="zh-CN">',
        )
    else:
        article = article.replace(
            'href="' + GH_BLOB + 'docs/PROJECT.md">',
            'href="project.html" hreflang="en" lang="en">',
        )
    return page_html(article, lang, source_rel, source_rel)


def main(argv):
    opts = parse_args(argv)
    if opts["source"] is not None:
        pairs = ((resolve(opts["source"]), resolve(opts["output"]), opts["lang"]),)
    else:
        pairs = DEFAULT_PAGES

    checked = 0
    generated = 0
    stale = 0
    for source, output, lang in pairs:
        if not source.is_file():
            sys.stderr.write(
                "generate_project_page: source missing, skipped: "
                + str(source.relative_to(ROOT)) + "\n"
            )
            continue
        output.parent.mkdir(parents=True, exist_ok=True)
        try:
            page = build_page(source, lang)
        except OSError as exc:
            fail("cannot read " + str(source) + ": " + str(exc))
            return 2
        checked += 1
        if opts["check"]:
            existing = output.read_text(encoding="utf-8") if output.is_file() else ""
            if existing != page:
                sys.stderr.write(
                    "generate_project_page: stale output: "
                    + str(output.relative_to(ROOT)) + " (re-run the generator)\n"
                )
                stale += 1
            continue
        output.write_text(page, encoding="utf-8")
        generated += 1
        print(
            "generated " + output.relative_to(ROOT).as_posix()
            + " (%d bytes, lang=%s)" % (len(page.encode("utf-8")), lang)
        )

    if checked == 0:
        fail("no project document sources found")
        return 2
    if opts["check"]:
        if stale:
            return 1
        print("up to date: %d page(s) checked" % checked)
        return 0
    if generated == 0:
        fail("nothing generated")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
